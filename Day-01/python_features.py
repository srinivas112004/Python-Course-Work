# - Code is executed line by line without compilation.

# 4. Object-Oriented
# - Supports Classes, Objects, Inheritance, Polymorphism,
#   Encapsulation, and Abstraction.

# 5. Open Source
# - Free to use and maintained by a large community.

# 6. Portable
# - Runs on Windows, Linux, macOS with little or no changes.

# 7. Dynamically Typed
# - Variable types are determined at runtime.

# 8. Large Community Support
# - Millions of developers contribute tutorials, libraries, and tools.

